#!/usr/bin/env python3
"""Build the space-group pages under symmetry/.

For each of the 230 space groups (standard setting, as in the International
Tables Vol. A and the Bilbao get_wp listing: unique axis b / cell choice 1,
origin choice 2, hexagonal axes for R groups) this writes

  symmetry/<n>/index.html   the group page: symmetry/group-template.html with the
                            group's operations and Wyckoff positions embedded
  symmetry/data/index.js    a summary of all groups, used by symmetry/index.html

Needs pyxtal and spglib:  pip install pyxtal spglib
Run:                      python3 scripts/build_symmetry.py
"""
from __future__ import annotations

import html
import json
import re
from pathlib import Path

import spglib
from pyxtal.symmetry import Group

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "symmetry"
TEMPLATE = OUT / "group-template.html"

# Well-known materials, shown as examples on the group page and in the browser.
EXAMPLES = {
    2: "many molecular crystals",
    4: "chiral molecular crystals, e.g. sucrose",
    14: "about a third of all organic molecular crystals",
    15: "many molecular crystals",
    19: "most common group for chiral molecules and proteins",
    61: "many organic crystals",
    62: "olivine (Mg,Fe)₂SiO₄; GdFeO₃-type perovskites",
    136: "rutile TiO₂",
    139: "ThCr₂Si₂-type compounds",
    141: "anatase TiO₂; zircon ZrSiO₄",
    152: "α-quartz SiO₂ (one enantiomorph)",
    154: "α-quartz SiO₂ (the other enantiomorph)",
    166: "Bi₂Te₃, Bi₂Se₃",
    167: "corundum Al₂O₃, calcite CaCO₃",
    186: "wurtzite ZnO, GaN",
    194: "graphite; hcp metals Mg, Ti, Zn",
    216: "zinc blende ZnS, GaAs",
    221: "CsCl; cubic perovskite SrTiO₃",
    225: "rock salt NaCl; fcc metals Cu, Al",
    227: "diamond, silicon; spinel MgAl₂O₄",
    229: "bcc metals α-Fe, W",
}


def clean(xyz: str) -> str:
    return xyz.replace(" ", "")


def group_data(n: int) -> dict:
    g = Group(n)
    t = spglib.get_spacegroup_type(g.hall_number)
    wyckoff = []
    for wp in g:  # general position first, then towards 'a'
        wp.get_site_symmetry()
        wyckoff.append({
            "m": wp.multiplicity,
            "l": wp.letter,
            "site": wp.site_symm,
            "coords": [clean(op.as_xyz_str()) for op in wp.ops],
        })
    return {
        "number": n,
        "short": t.international_short,
        "full": t.international_full,
        "system": g.lattice_type,
        "pointGroup": t.pointgroup_international,
        "choice": t.choice,
        "centrosymmetric": bool(g.inversion),
        "sohncke": bool(g.chiral),
        "polar": bool(g.polar),
        "example": EXAMPLES.get(n, ""),
        "ops": [clean(op.as_xyz_str()) for op in g[0].ops],
        "wyckoff": wyckoff,
    }


def hm_text(sym: str) -> str:
    """'P2_1/c' -> 'P2₁/c' for plain-text titles."""
    return re.sub(r"_(\d)", lambda m: "₀₁₂₃₄₅₆"[int(m.group(1))], sym)


def main() -> None:
    template = TEMPLATE.read_text()
    summary = []
    for n in range(1, 231):
        d = group_data(n)
        page = (template
                .replace("{{NUMBER}}", str(n))
                .replace("{{TITLE}}", html.escape(f"{hm_text(d['short'])} (No. {n})"))
                .replace("{{SYSTEM}}", d["system"])
                .replace("{{DATA}}", json.dumps(d, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")))
        (OUT / str(n)).mkdir(exist_ok=True)
        (OUT / str(n) / "index.html").write_text(page)
        summary.append({
            "n": n, "s": d["short"], "f": d["full"], "sys": d["system"], "pg": d["pointGroup"], "order": len(d["ops"]),
            "nw": len(d["wyckoff"]), "c": d["centrosymmetric"], "k": d["sohncke"], "ex": d["example"],
        })
        print(f"{n:3d} {d['short']:<12} {len(d['ops']):3d} ops  {len(d['wyckoff']):2d} Wyckoff positions")
    (OUT / "data").mkdir(exist_ok=True)
    (OUT / "data" / "index.js").write_text(
        "/* Generated by scripts/build_symmetry.py: one entry per space group. */\n"
        "window.SG_INDEX = " + json.dumps(summary, ensure_ascii=False, separators=(",", ":")) + ";\n")


if __name__ == "__main__":
    main()
